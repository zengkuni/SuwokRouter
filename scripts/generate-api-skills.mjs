// Generates SKILL.md — the Suwok Router API reference for the chat agent.
// Run: bun run skills:api
//
// Endpoint surface and auth classes are derived from the source of truth
// (src/routes/**/route.* for endpoints, src/dashboardGuard.js for auth
// classes) so the skill cannot silently drift from the implementation.

import fs from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..");
const ROUTES_DIR = path.join(ROOT, "src", "routes");
const GUARD_FILE = path.join(ROOT, "src", "dashboardGuard.js");

const HTTP_METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"];

function parseStringArray(source, name) {
  const match = source.match(new RegExp(`const ${name} = \\[([\\s\\S]*?)\\];`));
  if (!match) return [];
  return [...match[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

async function readGuardLists() {
  const source = await fs.readFile(GUARD_FILE, "utf8");
  return {
    public: parseStringArray(source, "PUBLIC_API_PATHS"),
    publicPrefixes: parseStringArray(source, "PUBLIC_PREFIXES"),
    alwaysProtected: parseStringArray(source, "ALWAYS_PROTECTED"),
    protected: parseStringArray(source, "PROTECTED_API_PATHS"),
    localOnly: parseStringArray(source, "LOCAL_ONLY_PATHS"),
  };
}

function classifyEndpoint(urlPath, guard) {
  if (guard.localOnly.some((p) => urlPath.startsWith(p))) return "local-only";
  if (guard.alwaysProtected.some((p) => urlPath === p)) return "always-protected";
  if (guard.public.some((p) => urlPath === p || urlPath.startsWith(`${p}/`))) return "public";
  if (guard.protected.some((p) => urlPath.startsWith(p))) return "dashboard/cli token";
  if (guard.publicPrefixes.some((p) => urlPath.startsWith(p))) return "public (gateway: API key unless loopback)";
  return "dashboard/cli token";
}

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full));
    else if (/^route\.(js|ts)$/.test(entry.name)) files.push(full);
  }
  return files;
}

function urlPathFor(file) {
  const rel = path.relative(ROUTES_DIR, file);
  const parts = path.dirname(rel).split(path.sep).filter(Boolean);
  const converted = parts.map((part) => {
    const dynamic = part.match(/^\[(.+)\]$/);
    return dynamic ? `{${dynamic[1]}}` : part;
  });
  return `/${converted.join("/")}`;
}

async function methodsFor(file) {
  const source = await fs.readFile(file, "utf8");
  return HTTP_METHODS.filter((method) =>
    new RegExp(`export\\s+(?:async\\s+)?function\\s+${method}\\b`).test(source));
}

const guard = await readGuardLists();
const files = (await walk(ROUTES_DIR)).sort();
const rows = [];
for (const file of files) {
  const urlPath = urlPathFor(file);
  const methods = await methodsFor(file);
  if (!methods.length) continue;
  rows.push({ urlPath, methods, auth: classifyEndpoint(urlPath, guard) });
}

const authOrder = [
  "public",
  "public (gateway: API key unless loopback)",
  "dashboard/cli token",
  "local-only",
  "always-protected",
];

const lines = [];
lines.push("# SuwokRouter API Skill");
lines.push("");
lines.push("<!-- Generated by scripts/generate-api-skills.mjs (bun run skills:api). Do not edit by hand. -->");
lines.push("");
lines.push("## How the chat agent should use this skill");
lines.push("");
lines.push("- **Source of truth:** models, combos, provider connections, usage, pricing, keys, and settings live in the router database (Postgres) — never in workspace files. Do not grep the workspace for combo/model definitions; query this API.");
lines.push("- **Base URL from the curl tool:** `http://127.0.0.1:12122` (the router's own port; default `12122`). Loopback calls to the router's own port are always allowed and automatically carry the internal CLI token — no API key needed. Writable methods (POST/PUT/PATCH/DELETE with a JSON `body` object) work only against this self URL, never against other hosts.");
lines.push("- **Reordering combo members:** `GET /api/combos` → locate the combo → `PUT /api/combos/{id}` with the full updated object `{ \"name\": \"...\", \"kind\": \"...\", \"group\": \"...\", \"models\": [...] }` (`group` is an optional display label; same label = one section in the Combos page). Array order IS the priority/fallback order, so send the members in the desired sequence and keep every existing field.");
lines.push("- **Auth classes** (enforced by `src/dashboardGuard.js`):");
lines.push("  - `public` — no credentials.");
lines.push("  - `public (gateway: API key unless loopback)` — the OpenAI-compatible gateway; remote callers need an API key, loopback callers do not.");
lines.push("  - `dashboard/cli token` — needs the dashboard session or the `x-suwokrouter-cli-token` header (attached automatically for the agent's own loopback calls).");
lines.push("  - `local-only` — loopback or trusted-local request with the CLI token; never accepts remote API keys.");
lines.push("  - `always-protected` — same, plus stored in the always-protected list (destructive/system routes).");
lines.push("- **Ranking procedure** (when asked to route by rank): GET `/api/combos` (ordered member models) or `/api/models` (rank/priority), check availability via `/api/usage` and `/api/providers`, pick the highest-priority available model, then state the choice with the tool evidence.");
lines.push("- **Shell tool syntax:** one read-only command per call — `rg [flags] pattern [paths...]`, `cat <file>`, `ls [-a] [dir]`, `pwd`, `git status|diff|log|show|branch`. Safe rg flags: `-i -l -n -w -F -c -t <type> -g <glob>`. No pipes, `&&`, `$( )`, or redirects.");
lines.push("- **Regenerate this file** after endpoint changes: `bun run skills:api`.");
lines.push("");
lines.push("## Endpoints");
lines.push("");
lines.push("| Method | Path | Auth |");
lines.push("| --- | --- | --- |");
for (const auth of authOrder) {
  for (const row of rows.filter((r) => r.auth === auth)) {
    for (const method of row.methods) {
      lines.push(`| ${method} | \`${row.urlPath}\` | ${row.auth} |`);
    }
  }
}
lines.push("");
lines.push(`_${rows.length} route modules, ${rows.reduce((n, r) => n + r.methods.length, 0)} methods._`);
lines.push("");

await fs.writeFile(path.join(ROOT, "SKILL.md"), `${lines.join("\n")}\r\n`);
console.log(`SKILL.md written: ${rows.length} routes`);
